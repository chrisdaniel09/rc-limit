-- 008: Loans module, loan files. The loan file and its state, its ledger of credits and debits,
-- the RC tracker, the application-number sequence and the outbox for journal postings.
-- See docs/Loans_Module_Enhancements.md and docs/loan_lifecycle_file_revamp_specification.md.

-- Next application number per tenant (APP-<year>-<number>).
CREATE TABLE public.application_number_sequences (
    tenant_id  UUID PRIMARY KEY,
    next_value BIGINT NOT NULL DEFAULT 1
);

-- loan_status follows the state machine in Domain/Rules/LoanStatuses.cs:
-- NEW -> DOCUMENTS_PENDING -> LOGGED_IN -> CREDIT_REVIEW -> SANCTIONED -> DISBURSED -> CLOSED,
-- with REJECTED and WITHDRAWN as terminal branches.
-- partner_id is a plain id: partners belong to the Partners module.
CREATE TABLE public.loan_transactions (
    loan_id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id               UUID          NOT NULL,
    serial_number           INT           GENERATED BY DEFAULT AS IDENTITY,
    application_number      VARCHAR(30)   NOT NULL,
    lender_agreement_number VARCHAR(50),
    customer_id             UUID          NOT NULL REFERENCES public.customers(customer_id),
    vehicle_id              UUID          NOT NULL REFERENCES public.vehicles(vehicle_id),
    pool_id                 UUID          NOT NULL REFERENCES public.master_bank_pools(pool_id),
    partner_id              UUID,
    product_type            VARCHAR(30)   NOT NULL DEFAULT 'USED_CV' CHECK (product_type IN ('USED_CV', 'NEW_CV', 'REFINANCE')),
    loan_status             VARCHAR(30)   NOT NULL DEFAULT 'NEW' CHECK (loan_status IN
                                ('NEW', 'DOCUMENTS_PENDING', 'LOGGED_IN', 'CREDIT_REVIEW', 'SANCTIONED',
                                 'REJECTED', 'WITHDRAWN', 'DISBURSED', 'CLOSED')),

    -- Amounts. sanctioned_amount is set at SANCTIONED. net_disbursed_amount is the Anna Finance balance.
    requested_amount        NUMERIC(15,2) NOT NULL CHECK (requested_amount > 0),
    sanctioned_amount       NUMERIC(15,2) CHECK (sanctioned_amount > 0),
    net_disbursed_amount    NUMERIC(15,2) NOT NULL DEFAULT 0.00,
    customer_rate           NUMERIC(5,2)  NOT NULL DEFAULT 0.00,
    tenure_months           INT,

    -- Payout commissions
    bank_payout_pct_amt     NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    bonus_payout_amt        NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    shared_payout_amt       NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_payout_earned     NUMERIC(10,2) NOT NULL GENERATED ALWAYS AS (bank_payout_pct_amt + bonus_payout_amt - shared_payout_amt) STORED,

    -- Milestones
    logged_in_date             DATE,
    sanction_date              DATE,
    disbursal_date             DATE,
    emi_start_date             DATE,
    emi_due_day                INT CHECK (emi_due_day BETWEEN 1 AND 31),
    pdd_due_date               DATE,
    closed_date                DATE,
    rejection_withdrawn_date   DATE,
    rejection_withdrawn_reason TEXT,

    post_disbursement_document_status_id UUID REFERENCES public.post_disbursement_document_statuses(document_status_id),
    remarks                 TEXT,
    created_by_user_id      UUID,
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ,

    CONSTRAINT ck_loan_transactions_sanction_amount
        CHECK (loan_status NOT IN ('SANCTIONED', 'DISBURSED', 'CLOSED') OR sanctioned_amount IS NOT NULL)
);

CREATE UNIQUE INDEX ix_loan_transactions_tenant_application_number ON public.loan_transactions(tenant_id, application_number);
CREATE INDEX idx_loans_tenant_created ON public.loan_transactions(tenant_id, created_at DESC, loan_id);
CREATE INDEX idx_loans_status ON public.loan_transactions(tenant_id, loan_status);
CREATE INDEX idx_loans_customer ON public.loan_transactions(customer_id);
CREATE INDEX idx_loans_vehicle ON public.loan_transactions(vehicle_id);
CREATE INDEX idx_loans_pool ON public.loan_transactions(pool_id);
CREATE INDEX idx_loans_partner ON public.loan_transactions(partner_id);

-- Ledger entries. A CREDIT is a bank payout to the counterparty. A DEBIT is a payout from the Anna Finance
-- balance. running_balance_amt is the Anna Finance balance after the entry.
CREATE TABLE public.disbursal_line_items (
    line_item_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    loan_id             UUID          NOT NULL REFERENCES public.loan_transactions(loan_id) ON DELETE CASCADE,
    entry_date          DATE          NOT NULL DEFAULT CURRENT_DATE,
    entry_direction     VARCHAR(10)   NOT NULL CONSTRAINT ck_disbursal_line_items_direction CHECK (entry_direction IN ('CREDIT', 'DEBIT')),
    counterparty        VARCHAR(50)   NOT NULL,
    particular_type     VARCHAR(50)   NOT NULL,
    mode_of_payment     VARCHAR(20),
    bank_name           VARCHAR(100),
    account_no          VARCHAR(50),
    transaction_id      VARCHAR(100),
    amount              NUMERIC(15,2) NOT NULL CONSTRAINT ck_disbursal_line_items_amount CHECK (amount > 0),
    running_balance_amt NUMERIC(15,2) NOT NULL CHECK (running_balance_amt >= 0),
    created_by_user_id  UUID,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_disbursal_items_loan_created ON public.disbursal_line_items(loan_id, created_at, line_item_id);

-- RC aging for used vehicles. Created at disbursal.
CREATE TABLE public.rc_pipeline_tracker (
    tracker_id       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    loan_id          UUID         NOT NULL UNIQUE REFERENCES public.loan_transactions(loan_id) ON DELETE CASCADE,
    current_stage    VARCHAR(50)  NOT NULL DEFAULT 'DISBURSED_PENDING_RTO',
    aging_status     VARCHAR(20)  NOT NULL DEFAULT 'ON_TIME',
    rto_ack_doc_url  VARCHAR(255),
    final_rc_doc_url VARCHAR(255),
    ack_uploaded_at  TIMESTAMPTZ,
    rc_cleared_at    TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ
);

CREATE INDEX idx_rc_tracker_stage ON public.rc_pipeline_tracker(current_stage);

-- Messages to other modules, written in the same transaction as the change that causes them.
-- The Loans outbox dispatcher publishes them and sets published_at.
CREATE TABLE public.outbox_messages (
    message_id   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id    UUID         NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    aggregate_id UUID         NOT NULL,
    payload      JSONB        NOT NULL,
    occurred_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    attempts     INT          NOT NULL DEFAULT 0,
    last_error   TEXT
);

CREATE INDEX idx_outbox_messages_unpublished ON public.outbox_messages(occurred_at) WHERE published_at IS NULL;
